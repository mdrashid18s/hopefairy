export default function Icon({ name, className = 'h-5 w-5', title, ...props }) {
  const Cmp = map[name] || Sparkles;
  const isAccessible = Boolean(title || props['aria-label']);
  return (
    <Cmp
      className={className}
      strokeWidth={1.75}
      aria-hidden={props['aria-hidden'] !== undefined ? props['aria-hidden'] : (isAccessible ? undefined : true)}
      role={isAccessible ? 'img' : undefined}
      {...(title ? { title } : {})}
      {...props}
    />
  );
}
